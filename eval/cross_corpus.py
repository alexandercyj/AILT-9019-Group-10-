#!/usr/bin/env python3
"""Every corpus, every record, both modes: does the pipeline hold on data it did not choose?

`eval/evaluate.py` scores the golden set: 17 hand-picked cases on the primary
corpus, with expectations written by the team. That is the right test for the
contract, and the wrong test for over-fitting — every expectation in it was
written while looking at the same 20 records.

This script asks a different question. It runs *every* record in *every*
registered corpus, with no per-record expectations, and reports only what the
pipeline says about itself: did it draft or refuse, did the four checks pass, and
did the model rewrite survive them. The third corpus is the point — Cleveland's
dates are phrased by Cleveland.

    python3 eval/cross_corpus.py              # offline, plus replay if transcripts exist
    python3 eval/cross_corpus.py --no-replay  # offline only
    python3 eval/cross_corpus.py --json

Writes eval/reports/cross_corpus.md. Exit code 0 when no drafted label failed a
check in either mode, 1 otherwise: a failing check on any record is a regression,
not a data quirk.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from labeldesk import __version__, load_corpus  # noqa: E402
from labeldesk.llm import prompt_hash  # noqa: E402
from labeldesk.pipeline import draft  # noqa: E402
from labeldesk.sources import aliases, provenance  # noqa: E402

REPORTS = ROOT / "eval" / "reports"


def run(corpus, llm=None) -> dict:
    counts: Counter = Counter()
    reasons: Counter = Counter()
    word_counts: list[int] = []
    sentences: list[float] = []
    failures: list[str] = []

    for record in corpus.records:
        result = draft(corpus, record["catalogue_number"], llm=llm)
        counts[result["status"]] += 1
        if result["status"] == "refused":
            reasons[result["reason"]] += 1
            continue
        counts["drafted_checks_passed"] += bool(result["checks"]["passed"])
        if not result["checks"]["passed"]:
            failures.append(f"{corpus.meta['name']}/{record['catalogue_number']}")
        word_counts.append(result["word_count"])
        sentences.append(result["checks"]["average_sentence_length"])
        block = result["llm"] or {}
        if block.get("requested"):
            if block["applied"]:
                counts["rewrite_accepted"] += 1
            else:
                counts["rewrite_discarded"] += 1
                reasons[f"discarded:{block['reason']}"] += 1

    return {
        "records": len(corpus),
        "counts": dict(counts),
        "reasons": dict(reasons),
        "mean_words": round(sum(word_counts) / len(word_counts), 1) if word_counts else None,
        "mean_sentence": round(sum(sentences) / len(sentences), 2) if sentences else None,
        "failures": failures,
    }


def render(rows: list[dict]) -> str:
    lines = [
        "# Cross-corpus run",
        "",
        f"Generated by `eval/cross_corpus.py` · Label Desk {__version__} · "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
        f"Prompt sha256 `{prompt_hash()[:12]}`",
        "",
        "Every record in every registered corpus, no per-record expectations. "
        "The numbers below are what the pipeline reports about itself.",
        "",
        "| corpus | records | drafted | refused | checks pass | rewrite accepted | discarded | mean words |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        offline = row["offline"]["counts"]
        llm = row["llm"]["counts"] if row["llm"] else {}
        lines.append(
            "| {name} | {records} | {drafted} | {refused} | {passed}/{drafted} | {acc} | {dis} | {words} |".format(
                name=row["alias"],
                records=row["offline"]["records"],
                drafted=offline.get("drafted", 0),
                refused=offline.get("refused", 0),
                passed=offline.get("drafted_checks_passed", 0),
                acc=llm.get("rewrite_accepted", "—"),
                dis=llm.get("rewrite_discarded", "—"),
                words=row["offline"]["mean_words"],
            )
        )

    lines += ["", "## Refusals, by reason", ""]
    for row in rows:
        for reason, count in sorted(row["offline"]["reasons"].items()):
            lines.append(f"- `{row['alias']}` · {reason} × {count}")
    if not any(row["offline"]["reasons"] for row in rows):
        lines.append("- none")

    lines += ["", "## Discarded rewrites, by reason", ""]
    discarded = [
        (row["alias"], reason, count)
        for row in rows
        if row["llm"]
        for reason, count in sorted(row["llm"]["reasons"].items())
        if reason.startswith("discarded:")
    ]
    if discarded:
        for alias, reason, count in discarded:
            lines.append(f"- `{alias}` · {reason.split(':', 1)[1]} × {count}")
    else:
        lines.append("- none")

    failures = [f for row in rows for f in row["offline"]["failures"]]
    failures += [f for row in rows if row["llm"] for f in row["llm"]["failures"]]
    lines += ["", "## Check failures", ""]
    lines += [f"- `{name}`" for name in failures] or ["- none"]

    lines += [
        "",
        "## What this does and does not show",
        "",
        "It shows that no record in any shipped corpus produces a label whose four "
        "checks fail, in either mode, and that the model layer is not tuned to one "
        "museum's phrasing. It does not show that the labels are good prose — a "
        "label can pass every check and still read badly, which is what curator "
        "review is for. The checks measure grounding, not taste.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--no-replay", action="store_true", help="skip the model replay run")
    parser.add_argument("--json", action="store_true", help="also dump JSON to stdout")
    args = parser.parse_args()

    rows = []
    for alias in sorted(aliases()):
        corpus = load_corpus(aliases()[alias])
        row = {"alias": alias, "offline": run(corpus)}
        if not args.no_replay:
            row["llm"] = run(corpus, llm="replay")
        row["provenance"] = provenance(corpus)
        rows.append(row)
        offline = row["offline"]["counts"]
        print(
            f"{alias:<10} {row['offline']['records']:>2} records · "
            f"{offline.get('drafted', 0)} drafted · {offline.get('refused', 0)} refused · "
            f"{offline.get('drafted_checks_passed', 0)}/{offline.get('drafted', 0)} checks pass"
            + (
                f" · rewrite {row['llm']['counts'].get('rewrite_accepted', 0)} accepted, "
                f"{row['llm']['counts'].get('rewrite_discarded', 0)} discarded"
                if row.get("llm")
                else ""
            )
        )

    text = render(rows)
    REPORTS.mkdir(parents=True, exist_ok=True)
    (REPORTS / "cross_corpus.md").write_text(text, encoding="utf-8")
    (REPORTS / "cross_corpus.json").write_text(
        json.dumps({"generated": datetime.now(timezone.utc).isoformat(), "runs": rows}, ensure_ascii=False, indent=2)
        + "\n",
        encoding="utf-8",
    )
    print(f"\nwrote eval/reports/cross_corpus.md")

    if args.json:
        print(json.dumps(rows, ensure_ascii=False, indent=2))

    failed = any(row["offline"]["failures"] for row in rows) or any(
        row.get("llm") and row["llm"]["failures"] for row in rows
    )
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
